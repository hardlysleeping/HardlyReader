#!/usr/bin/env bash
# Puts the background refresh into the iOS Xcode project.
#
# src-tauri/gen/apple does not exist on Linux — `tauri ios init` makes it, and
# only on a Mac — so the Swift files in src-tauri/ios cannot simply sit in the
# project. This runs on the Mac straight after `tauri ios init` and before
# `tauri ios build`:
#
#   1. copies the Swift and Objective-C halves into the generated project's
#      `Sources/` directory (a directory XcodeGen already scans);
#   2. re-runs XcodeGen so the files are in the target's compile sources;
#   3. proves the two halves actually landed — a file on disk that no target
#      compiles is a background refresh that never runs, and the failure would
#      otherwise only show up as "nothing happens" on a phone.
#
# The Info.plist keys are not written here: Tauri merges
# src-tauri/Info.ios.plist into the generated plist itself, during build.
#
# Set HR_IOS_NO_XCODEGEN=1 to skip the XcodeGen step; the Linux check uses that
# to exercise the copying and the checks against a stand-in project tree.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
source_dir="$root/src-tauri/ios"
project_dir="$root/src-tauri/gen/apple"

if [ ! -d "$project_dir" ] || [ ! -f "$project_dir/project.yml" ]; then
  echo "ios-background-refresh: $project_dir is not an XcodeGen project." >&2
  echo "  It is generated by 'pnpm tauri ios init', which only runs on a Mac." >&2
  exit 1
fi

if [ ! -d "$project_dir/Sources" ]; then
  echo "ios-background-refresh: $project_dir/Sources is missing." >&2
  echo "  XcodeGen's spec lists 'Sources' as a source path; without it the copied" >&2
  echo "  files would be compiled by nothing." >&2
  exit 1
fi

files=()
while IFS= read -r file; do files+=("$file"); done < <(
  find "$source_dir" -maxdepth 1 \( -name '*.swift' -o -name '*.m' \) -type f | sort
)

if [ ${#files[@]} -eq 0 ]; then
  echo "ios-background-refresh: no Swift or Objective-C files in $source_dir" >&2
  exit 1
fi

for file in "${files[@]}"; do
  echo "ios-background-refresh: copying $(basename "$file")"
  cp "$file" "$project_dir/Sources/"
done

if [ "${HR_IOS_NO_XCODEGEN:-0}" = "1" ]; then
  echo "ios-background-refresh: HR_IOS_NO_XCODEGEN=1, not regenerating the project"
elif command -v xcodegen >/dev/null 2>&1; then
  echo "ios-background-refresh: xcodegen generate"
  ( cd "$project_dir" && xcodegen generate )
else
  echo "ios-background-refresh: xcodegen is not installed (brew install xcodegen)" >&2
  exit 1
fi

# The proof: every copied file named in the project the build will actually use.
project_file=$(find "$project_dir" -maxdepth 2 -name project.pbxproj -print -quit)
if [ "${HR_IOS_NO_XCODEGEN:-0}" != "1" ] && [ -z "$project_file" ]; then
  echo "ios-background-refresh: no project.pbxproj under $project_dir" >&2
  exit 1
fi

status=0
for file in "${files[@]}"; do
  name=$(basename "$file")
  if [ "${HR_IOS_NO_XCODEGEN:-0}" = "1" ]; then
    [ -f "$project_dir/Sources/$name" ] || { echo "missing $name in Sources" >&2; status=1; }
    continue
  fi
  if ! grep -q "$name" "$project_file"; then
    echo "ios-background-refresh: $name is not in the Xcode project's compile sources" >&2
    status=1
  fi
done

if [ "$status" -ne 0 ]; then
  exit "$status"
fi

echo "ios-background-refresh: ${#files[@]} file(s) in place; the Info.plist keys come from src-tauri/Info.ios.plist during 'tauri ios build'"
