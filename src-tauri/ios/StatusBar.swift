import UIKit

/// The status bar belongs to portrait.
///
/// On its side a phone has no room to give away: the bar is 36px of controls at
/// the very top of the screen, and the clock, the wifi and the battery are drawn
/// **over** it — on an iPad the clock is additionally centred, which lands it in
/// the middle of the title. The stylesheet already reserves no strip for it in
/// landscape (see `app.css`, "Landscape reserves nothing at the top"), because
/// that is what a full-screen reading app looks like: the status bar should not
/// be there at all.
///
/// A WKWebView cannot ask for this. `UIViewController.basedStatusBarAppearance`
/// is a per-view-controller question and the view controller here belongs to
/// Tauri's generated template, which this project does not edit — it is a build
/// product regenerated by `tauri ios init` on every run. What is available is
/// the global switch: with `UIViewControllerBasedStatusBarAppearance = NO` in
/// the app's Info.plist (the release workflow sets it), iOS honours
/// `UIApplication.setStatusBarHidden(_:with:)` for the whole app, and the
/// orientation is the app's own business.
///
/// Deliberately landscape-only. In portrait the clock is where the header's
/// `--status-lift` arithmetic expects it, and hiding it there would leave a
/// band of nothing under the Dynamic Island.
///
/// `HardlyReaderStatusBar.marker` is a string constant so the release workflow
/// can prove this file was compiled into the binary — `strings` on the app
/// executable must contain `hardlyreader-status-bar-1`. A Swift file that never
/// entered the app target links nothing and fails silently.
enum HardlyReaderStatusBar {
  /// A release check reads this back out of the binary.
  static let marker = "hardlyreader-status-bar-1"

  private static var started = false

  /// Registered from `+load` on the class below, which is the earliest point
  /// that runs without being called by anybody.
  static func start() {
    guard !started else { return }
    started = true
    // Rotations are only delivered while this is on.
    UIDevice.current.beginGeneratingDeviceOrientationNotifications()
    let center = NotificationCenter.default
    // The first `didBecomeActive` is the launch: `+load` runs before there is a
    // window scene to ask about an orientation, so the answer is taken then.
    center.addObserver(
      forName: UIApplication.didBecomeActiveNotification,
      object: nil,
      queue: .main
    ) { _ in apply() }
    center.addObserver(
      forName: UIDevice.orientationDidChangeNotification,
      object: nil,
      queue: .main
    ) { _ in apply() }
  }

  /// Hide the bar when the frame is wider than it is tall.
  ///
  /// The scene's own `interfaceOrientation` rather than the screen's bounds: a
  /// screen's bounds do not rotate, so a landscape window on a portrait device
  /// asks the wrong question.
  private static func apply() {
    let scene = UIApplication.shared.connectedScenes
      .compactMap { $0 as? UIWindowScene }
      .first { $0.activationState == .foregroundActive || $0.activationState == .foregroundInactive }
      ?? UIApplication.shared.connectedScenes.compactMap { $0 as? UIWindowScene }.first
    let landscape = scene?.interfaceOrientation.isLandscape ?? false
    UIApplication.shared.setStatusBarHidden(landscape, with: .fade)
  }
}

/// `+load` runs for every class in a linked binary, before `main`, which is the
/// only hook that exists without editing Tauri's template.
final class HardlyReaderStatusBarHook: NSObject {
  @objc class func load() {
    HardlyReaderStatusBar.start()
  }
}
